import nodemailer from 'nodemailer';

const { MAIL_HOST, MAIL_PORT, MAIL_USER, MAIL_PASS, MAIL_FROM } = process.env;

const isMailConfigured = Boolean(
  MAIL_HOST && MAIL_PORT && MAIL_USER && MAIL_PASS
);

const transporter = isMailConfigured
  ? nodemailer.createTransport({
      host: MAIL_HOST,
      port: Number(MAIL_PORT),
      secure: Number(MAIL_PORT) === 465,
      auth: { user: MAIL_USER, pass: MAIL_PASS },
    })
  : null;

class MailerService {
  static async sendTemporaryPassword(email, temporaryPassword) {
    if (!transporter) {
      console.warn(
        `[mailer] SMTP not configured. Temporary password for ${email} was not emailed.`
      );
      return;
    }

    await transporter.sendMail({
      from: MAIL_FROM ?? MAIL_USER,
      to: email,
      subject: 'Tu acceso temporal a Adax',
      text:
        'Se registró tu expediente en Adax.\n\n' +
        `Tu contraseña temporal es: ${temporaryPassword}\n\n` +
        'Ingresa a la app con tu correo y esta contraseña, y cámbiala en tu primer inicio de sesión.',
    });
  }

  // G-09 / G-05: sends a 6-digit code for email verification or password recovery
  static async sendEmailCode(email, code, purpose) {
    if (!transporter) {
      console.warn(
        `[mailer] SMTP not configured. Code for ${email} was not sent.`
      );
      return;
    }

    const isReset = purpose === 'reset_password';
    const instruction = isReset
      ? 'Ingresa este código de 6 dígitos en la aplicación Adax Integra para recuperar tu contraseña.'
      : 'Ingresa este código de 6 dígitos en la aplicación Adax Integra para completar tu registro.';
    const ignoreNote = isReset
      ? 'Si no solicitaste recuperar tu contraseña, puedes ignorar este mensaje.'
      : 'Si no solicitaste este registro, puedes ignorar este mensaje.';

    await transporter.sendMail({
      from: MAIL_FROM ?? MAIL_USER,
      to: email,
      subject: isReset
        ? 'Tu código para recuperar tu contraseña de Adax'
        : 'Tu código de verificación de Adax',
      // plain text fallback for clients that do not render HTML
      text:
        `Tu código de confirmación es: ${code}\n\n` +
        `${instruction}\n` +
        'El código vence en 15 minutos.\n\n' +
        ignoreNote,
      // code is always 6 digits generated by EmailCodeService, so it is safe to insert
      html: `
       <div style="max-width: 400px; margin: 0 auto; padding: 28px 20px; background: #ffffff; border-radius: 12px; border: 1px solid #eae6ee; font-family: system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif; text-align: center; color: #2d2d2d;">
  <h2 style="margin: 0 0 16px; font-size: 18px; font-weight: 600; color: #1a1a1a;">Tu código de confirmación</h2>
  
  <div style="background: #f7f0fa; border: 1px dashed #6C2582; border-radius: 8px; padding: 14px 0; margin: 16px 0;">
    <span style="font-size: 32px; font-weight: bold; letter-spacing: 6px; color: #6C2582; font-family: monospace;">${code}</span>
  </div>

  <p style="margin: 0 0 12px; font-size: 14px; line-height: 1.5; color: #555555;">${instruction}</p>
  <p style="margin: 0 0 12px; font-size: 13px; color: #666666;">El código vence en <strong>15 minutos</strong>.</p>
  <p style="margin: 16px 0 0; font-size: 12px; color: #999999; line-height: 1.4;">${ignoreNote}</p>
</div>
      `,
    });
  }

  // G-07: tells the external user her data changed without listing the new
  // values, in case someone else has access to her inbox
  static async sendProfileUpdatedNotice(email) {
    if (!transporter) {
      console.warn(
        `[mailer] SMTP not configured. Profile update notice for ${email} was not emailed.`
      );
      return;
    }

    const message = 'Te informamos que el equipo de Adax actualizó los datos de tu cuenta con tu autorización.';
    const contactNote = 'Si no reconoces este cambio, siéntete libre de comunicarte con Adax por sus medios oficiales.';

    await transporter.sendMail({
      from: MAIL_FROM ?? MAIL_USER,
      to: email,
      subject: 'Actualización de tus datos en Adax',
      // plain text fallback for clients that do not render HTML
      text: `${message}\n\n${contactNote}`,
      // only fixed text is inserted, no user data
      html: `
        <div style="max-width: 400px; margin: 0 auto; padding: 28px 20px; background: #ffffff; border-radius: 12px; border: 1px solid #eae6ee; font-family: system-ui, -apple-system, 'Segoe UI', Roboto, sans-serif; text-align: center; color: #2d2d2d;">
          <h2 style="margin: 0 0 16px; font-size: 18px; font-weight: 600; color: #6C2582;">Actualización de tus datos</h2>
          <p style="margin: 0 0 12px; font-size: 14px; line-height: 1.5; color: #555555;">${message}</p>
          <p style="margin: 16px 0 0; font-size: 12px; color: #999999; line-height: 1.4;">${contactNote}</p>
        </div>
      `,
    });
  }

  // B-02: tells the external user their account was verified by staff
  static async sendAccountVerifiedNotice(email) {
    if (!transporter) {
      console.warn(
        `[mailer] SMTP not configured. Account verified notice for ${email} was not emailed.`
      );
      return;
    }

    await transporter.sendMail({
      from: MAIL_FROM ?? MAIL_USER,
      to: email,
      subject: 'Tu cuenta de Adax fue verificada',
      text:
        'Buenas noticias: el equipo de Adax revisó tus documentos y tu cuenta quedó verificada.\n\n' +
        'Ya tienes acceso completo a la plataforma. Si no reconoces este cambio, comunícate con Adax por sus medios oficiales.',
    });
  }

  // B-02: tells the external user their documents were rejected and need to be sent again
  static async sendVerificationRejectedNotice(email, reason) {
    if (!transporter) {
      console.warn(
        `[mailer] SMTP not configured. Verification rejected notice for ${email} was not emailed.`
      );
      return;
    }

    const reasonLine = reason ? `\n\nMotivo: ${reason}` : '';

    await transporter.sendMail({
      from: MAIL_FROM ?? MAIL_USER,
      to: email,
      subject: 'Revisión de tus documentos en Adax',
      text:
        'El equipo de Adax revisó tus documentos y necesitamos que los vuelvas a enviar.' +
        reasonLine +
        '\n\nIngresa a la aplicación y sube de nuevo tu comprobante de identidad y tu comprobante de domicilio. ' +
        'Si tienes dudas, comunícate con Adax por sus medios oficiales.',
    });
  }
}

export default MailerService;
